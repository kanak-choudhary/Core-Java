public class evenOdd {
    public static void main(String[] args) {

        int num=42; // 


        if (num%2==0) {  //  42/2=21 > % = 0
                         // 43/2=21.5 > %= 0.5
            System.out.println(num+ " is even number");
        }

        else{
            System.out.println(num + " is odd number ");
        }
    }
}


