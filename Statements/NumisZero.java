// Check whether a number is less than 0, equal to 0, or greater than 0.

public class NumisZero {
    public static void main(String[] args) {
        
        int num=-8;

        if (num==0) {
            System.out.println(num + " is equal to zero");
        }
        else if (num >0) {
            System.out.println(num + " is greater than zero");
        }
         else if (num < 0) {
            System.out.println(num + " is less than zero");
        }
        

    }
}
